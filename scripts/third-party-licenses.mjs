// Regenerates public/THIRD_PARTY_LICENSES.txt — the license texts of every
// production dependency, which the build copies into dist/ so each packaged
// extension carries the notices its bundled code requires.
// Run after changing dependencies: `npm run licenses`.
import { execFileSync } from "node:child_process";
import { existsSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { join, relative } from "node:path";

const root = process.cwd();
const paths = execFileSync("npm", ["ls", "--omit=dev", "--all", "--parseable"], { cwd: root, encoding: "utf8" })
  .split("\n")
  .map((p) => p.trim())
  .filter((p) => p && p !== root && existsSync(join(p, "package.json")));

const sections = [...new Set(paths)]
  .map((dir) => {
    const pkg = JSON.parse(readFileSync(join(dir, "package.json"), "utf8"));
    const file = readdirSync(dir).find((f) => /^(licen[cs]e|copying)(\.|$)/i.test(f));
    const text = file ? readFileSync(join(dir, file), "utf8").trim() : `License: ${pkg.license ?? "see package"} (no license file in the package)`;
    return { name: pkg.name ?? relative(root, dir), version: pkg.version ?? "", license: pkg.license ?? "", text };
  })
  .sort((a, b) => a.name.localeCompare(b.name));

const rule = "-".repeat(78);
const body = [
  "Third-party software bundled with SN AI Copilot",
  "",
  "Generated by scripts/third-party-licenses.mjs from the production dependencies.",
  "SheetJS Community Edition (xlsx.mini.min.js) is listed separately in xlsx.LICENSE.txt.",
  "",
  ...sections.flatMap((s) => [rule, `${s.name} ${s.version}${s.license ? ` — ${s.license}` : ""}`, rule, "", s.text, ""]),
].join("\n");

writeFileSync(join(root, "public", "THIRD_PARTY_LICENSES.txt"), body + "\n");
console.log(`Wrote public/THIRD_PARTY_LICENSES.txt (${sections.length} packages)`);
